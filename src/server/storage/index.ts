import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Private object storage for uploads. Objects are addressed only by random keys that the database maps to
 * an owner; nothing here is ever served directly. The local-disk driver is for development and
 * single-instance deployments; an S3-compatible driver (MinIO locally, per the architecture doc) can
 * implement the same interface.
 */
export interface Storage {
  put(bytes: Uint8Array): Promise<string>;
  get(key: string): Promise<Uint8Array | null>;
  /** Idempotent: deleting a missing object succeeds. */
  delete(key: string): Promise<void>;
}

const KEY_RE = /^[0-9a-f]{2}\/[0-9a-f-]{36}$/;

export function createLocalStorage(rootDir: string): Storage {
  const root = path.resolve(rootDir);
  const resolve = (key: string) => {
    // Keys are generated by put(); reject anything else so a bad DB value can't escape the root.
    if (!KEY_RE.test(key)) throw new Error("invalid storage key");
    const full = path.resolve(root, key);
    if (!full.startsWith(root + path.sep)) throw new Error("invalid storage key");
    return full;
  };
  return {
    async put(bytes) {
      const id = randomUUID();
      const key = `${id.slice(0, 2)}/${id}`;
      const full = resolve(key);
      await mkdir(path.dirname(full), { recursive: true });
      await writeFile(full, bytes, { flag: "wx", mode: 0o600 });
      return key;
    },
    async get(key) {
      try {
        return new Uint8Array(await readFile(resolve(key)));
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw e;
      }
    },
    async delete(key) {
      await rm(resolve(key), { force: true });
    },
  };
}

let singleton: Storage | undefined;

/** Production wiring. Tests construct their own storage in a temp directory. */
export function getStorage(): Storage {
  singleton ??= createLocalStorage(
    process.env.UPLOAD_DIR || path.join(process.cwd(), ".data", "uploads"),
  );
  return singleton;
}
